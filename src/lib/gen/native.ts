import type { M3EConfig } from '@/lib/m3e/config';
import { prefixFor } from '@/lib/m3e/config';
import { buildTheme } from '@/lib/m3e/css';
import { M3E_COLOR_ROLES, type M3EColorRole } from '@/lib/m3e/roles';
import type { GenFile } from './common';

/** Extra export targets beyond the web frameworks (added on top of a FW bundle). */
export const EXPORT_TARGETS = ['style-dictionary', 'compose', 'android-xml'] as const;
export type ExportTarget = (typeof EXPORT_TARGETS)[number];

export const EXPORT_TARGET_LABELS: Record<ExportTarget, string> = {
  'style-dictionary': 'Style Dictionary',
  compose: 'Compose (Kotlin)',
  'android-xml': 'Android XML',
};

const camel = (role: M3EColorRole): string =>
  role.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());

/** 0xFFRRGGBB / #FFRRGGBB from `#rrggbb` */
function argb(hex: string): string {
  return `FF${hex.replace('#', '').toUpperCase()}`;
}

function hexOf(vars: Record<string, string>, naming: M3EConfig['naming'], role: M3EColorRole) {
  return vars[`--${prefixFor(naming)}-color-${role}`] ?? '#000000';
}

/** Roles that exist on androidx Compose MaterialTheme.colorScheme (ColorScheme ctor). */
