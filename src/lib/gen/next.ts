import {
  banner,
  generateReadme,
  generateThemeTs,
  generateTokensCss,
  generateTokensJsonFile,
  type GenContext,
  type GenFile,
} from './common';

export function nextFiles(ctx: GenContext): GenFile[] {
  const globals = generateTokensCss(ctx, { withTailwind: true });
  const demoButton = `import type { ReactNode } from 'react';

/** M3E filled button — pill shape, spring press morph, state layer */
export function Button({ children, variant = 'filled' }: { children: ReactNode; variant?: 'filled' | 'tonal' | 'outlined' }) {
  const look = {
    filled: 'bg-primary text-on-primary',
    tonal: 'bg-secondary-container text-on-secondary-container',
    outlined: 'border border-outline text-primary',
  }[variant];
  return (
    <button
      type="button"
      className={
        'm3e-press group relative inline-flex h-10 items-center justify-center gap-2 overflow-hidden rounded-button px-6 text-label-large ' +
        'active:scale-[0.95] active:rounded-medium ' +
        look
      }
    >
      <span className="pointer-events-none absolute inset-0 bg-current opacity-0 transition-opacity group-hover:opacity-[0.08]" />
      {children}
    </button>
  );
}
`;

  const layout = `${banner(ctx, 'Root layout')}
import type { Metadata, Viewport } from 'next';
import './globals.css';
import { ThemeToggle } from '@/components/ThemeToggle';

export const metadata: Metadata = { title: 'My Material 3 Expressive app' };
export const viewport: Viewport = { themeColor: '#141218' };

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        {/* apply persisted light/dark mode before paint (no flash) */}
        <script
          dangerouslySetInnerHTML={{
            __html:
              "try{const m=localStorage.getItem('m3e-theme');if(m==='dark'||(!m&&matchMedia('(prefers-color-scheme: dark)').matches))document.documentElement.classList.add('dark');}catch(e){}",
          }}
        />
      </head>
      <body className="bg-background font-sans text-on-background">{children}</body>
    </html>
  );
}
`;

  const page = `${banner(ctx, 'Example page')}
import { Button } from '@/components/Button';

export default function Home() {
  return (
    <main className="flex min-h-dvh items-center justify-center p-6">
      <section className="w-full max-w-md rounded-card bg-surface-container p-6 shadow-sm">
        <p className="t-label-large text-primary">Now playing</p>
        <h1 className="t-display-small text-on-surface">Expressive Motion</h1>
        <p className="t-body-medium text-on-surface-variant">
          Tokens generated by M3E Studio — color, shape, typography and spring motion.
        </p>
        <div className="mt-6 flex flex-wrap items-center gap-3">
          <Button>Play</Button>
          <Button variant="tonal">Queue</Button>
          <Button variant="outlined">Share</Button>
        </div>
      </section>
    </main>
  );
}
`;

  const toggle = `'use client';

import { useEffect, useState } from 'react';
import { getStoredM3eMode, setM3eMode } from '@/lib/theme';

export function ThemeToggle() {
  const [dark, setDark] = useState(false);
  useEffect(() => {
    setDark(getStoredM3eMode() === 'dark');
  }, []);
  return (
    <button
      type="button"
      aria-label="Toggle dark mode"
      onClick={() => {
        const next = !dark ? 'dark' : 'light';
        setM3eMode(next);
        setDark(next === 'dark');
      }}
      className="m3e-press fixed right-6 bottom-6 flex h-14 w-14 items-center justify-center rounded-fab bg-tertiary-container text-on-tertiary-container active:scale-90 active:rounded-extra-large"
    >
      <span className="material-symbols-rounded">{dark ? 'light_mode' : 'dark_mode'}</span>
    </button>
  );
}
`;

  return [
    { path: 'app/globals.css', lang: 'css', content: globals },
    { path: 'app/layout.tsx', lang: 'tsx', content: layout },
    { path: 'app/page.tsx', lang: 'tsx', content: page },
    { path: 'components/Button.tsx', lang: 'tsx', content: demoButton },
    { path: 'components/ThemeToggle.tsx', lang: 'tsx', content: toggle },
    generateThemeTs(ctx, 'lib/theme.ts'),
    generateTokensJsonFile(ctx),
    generateReadme(ctx, {
      framework: 'Next.js (App Router) + Tailwind v4',
      steps: [
        'Scaffold: `npx create-next-app@latest my-app --ts --tailwind --eslint --app --src-dir` (see command table below for bun/pnpm/yarn)',
        'Replace `src/app/globals.css` with the generated file (it contains `@import "tailwindcss"`, all M3E tokens and the `@theme inline` mapping)',
        'Copy `layout.tsx` / `page.tsx` / components / lib/theme.ts into `src/`',
        'Run the dev server and toggle light/dark with the FAB',
      ],
      files: [
        { path: 'src/app/globals.css', purpose: 'Tailwind entry + M3E tokens + theme mapping' },
        { path: 'src/app/layout.tsx', purpose: 'pre-paint theme script, fonts' },
        { path: 'src/components/Button.tsx', purpose: 'reference expressive button' },
        { path: 'src/components/ThemeToggle.tsx', purpose: 'FAB theme toggle' },
        { path: 'src/lib/theme.ts', purpose: 'mode helpers + raw token vars' },
        { path: 'tokens.json', purpose: 'W3C DTCG tokens for design tools' },
      ],
    }),
  ];
}
