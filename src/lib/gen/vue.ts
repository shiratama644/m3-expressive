import {
  fontDeps,
  generateReadme,
  generateThemeTs,
  generateTokensCss,
  generateTokensJsonFile,
  type GenContext,
  type GenFile,
} from './common';
import { PM } from './pm';

export function vueFiles(ctx: GenContext): GenFile[] {
  const tokens = generateTokensCss(ctx, { withTailwind: true });
  const deps = [
    'tailwindcss',
    '@tailwindcss/vite',
    ...fontDeps(ctx.config.typeFamily).runtime,
  ].filter(Boolean);

  const app = `<!-- generated by M3E Studio — Material 3 Expressive -->
<script setup lang="ts">
import { useM3eTheme } from './composables/useM3eTheme';

const { dark, toggle } = useM3eTheme();
</script>

<template>
  <main class="flex min-h-dvh flex-col items-center justify-center gap-6 bg-background p-6 text-on-background">
    <section class="w-full max-w-md rounded-card bg-surface-container p-6">
      <p class="t-label-large text-primary">Material 3 Expressive</p>
      <h1 class="t-display-small">Vue + M3E</h1>
      <p class="t-body-medium mt-2 text-on-surface-variant">
        Every color, radius and spring is a CSS variable — Vue never re-renders for the theme.
      </p>
      <button
        type="button"
        class="m3e-press mt-6 inline-flex h-10 items-center gap-2 rounded-button bg-primary px-6 t-label-large text-on-primary active:scale-[0.95] active:rounded-medium"
        @click="toggle"
      >
        {{ dark ? 'Light mode' : 'Dark mode' }}
      </button>
    </section>
  </main>
</template>
`;

  const composable = `import { computed, ref, watchEffect } from 'vue';

type Mode = 'light' | 'dark';

function stored(): Mode {
  const s = localStorage.getItem('m3e-theme');
  if (s === 'light' || s === 'dark') return s;
  return matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
}

const mode = ref<Mode>(stored());

watchEffect(() => {
  document.documentElement.classList.toggle('dark', mode.value === 'dark');
  localStorage.setItem('m3e-theme', mode.value);
});

export function useM3eTheme() {
  return {
    dark: computed(() => mode.value === 'dark'),
    toggle: () => (mode.value = mode.value === 'dark' ? 'light' : 'dark'),
    mode,
  };
}
`;

  const mainTs = `import { createApp } from 'vue';
import App from './App.vue';
import './styles/tokens.css';

createApp(App).mount('#app');
`;

  return [
    { path: 'src/styles/tokens.css', lang: 'css', content: tokens },
    { path: 'src/App.vue', lang: 'vue', content: app },
    { path: 'src/composables/useM3eTheme.ts', lang: 'ts', content: composable },
    { path: 'src/main.ts', lang: 'ts', content: mainTs },
    generateThemeTs(ctx, 'src/theme.ts'),
    generateTokensJsonFile(ctx),
    generateReadme(ctx, {
      framework: 'Vue 3 (Vite) + Tailwind v4',
      steps: [
        `Scaffold: \`${PM[ctx.pm].create('vite my-app -- --template vue-ts')}\``,
        `Add Tailwind + fonts: \`${PM[ctx.pm].add(deps)}\``,
        'Register `@tailwindcss/vite` in `vite.config.ts`',
        'Copy the files below, import `src/styles/tokens.css` from `main.ts`',
        `Run: \`${PM[ctx.pm].run('dev')}\``,
      ],
      files: [
        { path: 'src/styles/tokens.css', purpose: 'Tailwind entry + all M3E tokens' },
        { path: 'src/composables/useM3eTheme.ts', purpose: 'light/dark composable' },
        { path: 'src/theme.ts', purpose: 'raw vars + mode helpers' },
        { path: 'tokens.json', purpose: 'W3C DTCG tokens' },
      ],
    }),
  ];
}
