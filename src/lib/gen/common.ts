import type { M3EConfig } from '@/lib/m3e/config';
import { buildTheme, renderThemeCss, type ThemeBundle } from '@/lib/m3e/css';
import { generateTokensJson } from '@/lib/m3e/tokensJson';
import { TYPE_ROLES } from '@/lib/m3e/typography';
import { type PackageManager, PM } from './pm';

export interface GenFile {
  /** e.g. "src/theme/tokens.css" */
  path: string;
  lang: 'css' | 'ts' | 'tsx' | 'vue' | 'html' | 'md' | 'json' | 'js' | 'kotlin' | 'xml';
  content: string;
}

export interface GenContext {
  config: M3EConfig;
  bundle: ThemeBundle;
  pm: PackageManager;
  prefix: string;
}

export function makeContext(config: M3EConfig, pm: PackageManager): GenContext {
  const bundle = buildTheme(config);
  const prefix = config.naming === 'md-sys' ? 'md-sys' : 'm3e';
  return { config, bundle, pm, prefix };
}

/** Header banner placed on every generated file. */
export function banner(ctx: GenContext, what: string): string {
  const { config } = ctx;
  return [
    `/* ${what} — generated by M3E Studio (Material 3 Expressive) */`,
    `/* seed ${config.seed} · variant ${config.variant} · contrast ${config.contrast} · shape ${config.shapeEmphasis} */`,
    `/* motion ${config.motionScheme}${config.useSprings ? '+springs' : ''} · type ${config.typeFamily}@${config.typeScale} · naming --${ctx.prefix}-* */`,
  ].join('\n');
}

const fontImports: Record<M3EConfig['typeFamily'], string> = {
  'roboto-flex': `@import '@fontsource-variable/roboto-flex/full.css';`,
  roboto: `@import '@fontsource/roboto/400.css';\n@import '@fontsource/roboto/500.css';\n@import '@fontsource/roboto/700.css';`,
  system: `/* system font stack selected — no webfont import needed */`,
};

export function fontDeps(family: M3EConfig['typeFamily']): { runtime: string[]; note?: string } {
  if (family === 'roboto-flex') return { runtime: ['@fontsource-variable/roboto-flex'] };
  if (family === 'roboto') return { runtime: ['@fontsource/roboto'] };
  return { runtime: [] };
}

/**
 * The core stylesheet for Tailwind v4 projects:
 *   font imports + `@import "tailwindcss"` + @theme mapping + raw token vars
 *   + `.t-*` utilities + expressive keyframes.
 */
export function generateTokensCss(ctx: GenContext, opts: { withTailwind: boolean }): string {
  const { bundle, prefix, config } = ctx;
  const p = prefix;
  const parts: string[] = [banner(ctx, 'Material 3 Expressive theme')];

  parts.push(config.typeFamily === 'system' ? fontImports.system : fontImports[config.typeFamily]);
  parts.push(`@import '@fontsource-variable/material-symbols-rounded/full.css';`);
  if (opts.withTailwind) parts.push(`@import 'tailwindcss';`);

  parts.push(renderThemeCss(bundle, { darkMode: 'class', tailwindTheme: opts.withTailwind }));

  // .t-* utilities (framework-agnostic typography)
  const tUtils = TYPE_ROLES.map(
    (role) => `.t-${role} {
  font-family: var(--${p}-typescale-${role}-font);
  font-size: var(--${p}-typescale-${role}-size);
  line-height: var(--${p}-typescale-${role}-line-height);
  letter-spacing: var(--${p}-typescale-${role}-letter-spacing);
  font-weight: var(--${p}-typescale-${role}-weight);
}`,
  ).join('\n');
  parts.push(`/* type-scale utilities */\n${tUtils}`);

  // shared demo CSS: state layers, press motion, keyframes
  parts.push(`/* expressive motion helpers */
.m3e-press {
  transition:
    transform var(--${p}-motion-spring-fast-spatial-duration) var(--${p}-motion-spring-fast-spatial-easing),
    border-radius var(--${p}-motion-spring-fast-spatial-duration) var(--${p}-motion-spring-fast-spatial-easing),
    background-color var(--${p}-motion-spring-default-effects-duration) var(--${p}-motion-spring-default-effects-easing),
    color var(--${p}-motion-spring-default-effects-duration) var(--${p}-motion-spring-default-effects-easing),
    box-shadow var(--${p}-motion-spring-default-effects-duration) var(--${p}-motion-spring-default-effects-easing);
}
@keyframes m3e-spin {
  to {
    transform: rotate(360deg);
  }
}
@media (prefers-reduced-motion: reduce) {
  .m3e-press {
    transition-duration: 0.01ms;
  }
}`);

  return `${parts.join('\n\n')}\n`;
}

export function generateTokensJsonFile(ctx: GenContext): GenFile {
  return { path: 'tokens.json', lang: 'json', content: generateTokensJson(ctx.config) };
}

/** JS/TS module exporting the vars (typed `CSSProperties`-friendly). */
export function generateThemeTs(ctx: GenContext, path = 'theme.ts'): GenFile {
  const contentFile = buildThemeTs(ctx);
  return { ...contentFile, path };
}

function buildThemeTs(ctx: GenContext): GenFile {
  const light = JSON.stringify({ ...ctx.bundle.shared, ...ctx.bundle.light }, null, 2);
  const dark = JSON.stringify({ ...ctx.bundle.shared, ...ctx.bundle.dark }, null, 2);
  const content = `${tsBanner(ctx)}
export const m3eLightVars = ${light} as Record<string, string>;
export const m3eDarkVars = ${dark} as Record<string, string>;

/** Apply the theme vars directly on <html> (no stylesheet required). */
export function applyM3eVars(mode: 'light' | 'dark') {
  const vars = mode === 'dark' ? m3eDarkVars : m3eLightVars;
  const el = document.documentElement;
  for (const [name, value] of Object.entries(vars)) el.style.setProperty(name, value);
}

/** Toggle the \`dark\` class used by the token stylesheet. */
export function setM3eMode(mode: 'light' | 'dark') {
  document.documentElement.classList.toggle('dark', mode === 'dark');
  localStorage.setItem('m3e-theme', mode);
}

export function getStoredM3eMode(): 'light' | 'dark' {
  const stored = localStorage.getItem('m3e-theme');
  if (stored === 'light' || stored === 'dark') return stored;
  return matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
}
`;
  return { path: 'theme.ts', lang: 'ts', content };
}

function tsBanner(ctx: GenContext) {
  const b = banner(ctx, 'Material 3 Expressive theme');
  // convert /* */ CSS banner to a comment-safe form for TS files
  return b.replace(/\/\* /g, '// ').replace(/ \*\//g, '');
}

/** README with setup steps for the chosen PM (+ full 4-PM table). */
export function generateReadme(
  ctx: GenContext,
  opts: { framework: string; steps: string[]; files: { path: string; purpose: string }[] },
): GenFile {
  const { pm } = ctx;
  const deps = fontDeps(ctx.config.typeFamily).runtime;
  const pmCommands = (['#', 'install', 'dev', 'build'] as const)
    .map((key) => {
      const label = { install: 'Install', dev: 'Dev server', build: 'Production build' }[
        key === '#' ? 'install' : key
      ];
      const cmd =
        key === 'install'
          ? deps.length
            ? PM[pm].add(deps)
            : PM[pm].install()
          : key === 'dev'
            ? PM[pm].run('dev')
            : PM[pm].run('build');
      return `| ${label} | \`${cmd}\` |`;
    })
    .join('\n');

  const allPmTable = ['bun', 'pnpm', 'npm', 'yarn']
    .map(
      (p) =>
        `| ${p === 'bun' ? 'Bun' : p === 'npm' ? 'npm' : p === 'yarn' ? 'Yarn' : 'pnpm'} | \`${deps.length ? PM[p as PackageManager].add(deps) : PM[p as PackageManager].install()}\` | \`${PM[p as PackageManager].run('dev')}\` |`,
    )
    .join('\n');

  const content = `# Material 3 Expressive theme — ${opts.framework}

> Generated by **M3E Studio** — https://github.com/shiratama644/m3-expressive
> Tokens follow the Material 3 Expressive (2025) spec: color (HCT dynamic color),
> shape, typography (Roboto Flex) and motion (springs expressed as CSS \`linear()\`).

## Setup

${opts.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}

## Commands (${pm})

| Task | Command |
| --- | --- |
${pmCommands}

All package managers work — swap the commands as needed:

| PM | Add fonts/tokens | Dev |
| --- | --- | --- |
${allPmTable}

## Files

| File | Purpose |
| --- | --- |
${opts.files.map((f) => `| \`${f.path}\` | ${f.purpose} |`).join('\n')}

## Theme switching

Toggle light/dark by adding or removing the \`dark\` class on \`<html>\`:

\`\`\`js
document.documentElement.classList.toggle('dark'); // persisted via theme.ts
\`\`\`

## Notes

- Colors are computed with the official HCT implementation (\`@material/material-color-utilities\`).
- \`prefers-reduced-motion: reduce\` is respected by the generated CSS.
- Material 3 Expressive™ is a Google design language (Apache 2.0 / CC-BY 4.0 documentation).
  Generated tokens are values, not code copied from Google SDKs — use freely, MIT-style.
`;
  return { path: 'README.md', lang: 'md', content };
}
